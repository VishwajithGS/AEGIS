"""Synthetic world model used by the data generator.

Everything here is SIMULATED. The model is a deliberately simple, documented
toy so that generated streams are internally consistent (rain causes rising
rivers, slower traffic and more incident reports):

* ``SensorNetwork`` - fixed synthetic weather stations, river gauges and
  traffic segments placed on land inside the study region.
* ``Storm`` - a moving Gaussian rain cell with a sine-shaped life cycle.
* ``Environment`` - latent rain field, per-location "wetness" (exponentially
  weighted accumulated rain), river levels and flood hazard.

None of the stations, rivers or storms correspond to real infrastructure.
"""
from __future__ import annotations

import math
import random
from dataclasses import dataclass, field
from typing import Iterable

from aegis.geo import ZoneGrid, haversine_km, is_on_land

KM_PER_DEG_LAT = 111.32

# Synthetic river polylines (lat, lon) - illustrative only, not real rivers.
SYNTHETIC_RIVERS = {
    "RIVER-A": [(13.080, 80.110), (13.075, 80.160), (13.072, 80.210), (13.078, 80.265)],
    "RIVER-B": [(13.010, 80.115), (13.012, 80.165), (13.008, 80.215), (13.004, 80.255)],
    "CANAL-C": [(12.880, 80.240), (12.960, 80.247), (13.040, 80.262), (13.140, 80.284), (13.220, 80.300)],
}


def _interp_polyline(points: list[tuple[float, float]], t: float) -> tuple[float, float]:
    """Point at fraction ``t`` (0..1) along a polyline (by segment count)."""
    t = max(0.0, min(1.0, t))
    n = len(points) - 1
    pos = t * n
    i = min(int(pos), n - 1)
    f = pos - i
    (a_lat, a_lon), (b_lat, b_lon) = points[i], points[i + 1]
    return a_lat + (b_lat - a_lat) * f, a_lon + (b_lon - a_lon) * f


@dataclass
class SensorNetwork:
    weather_stations: list[dict]
    water_stations: list[dict]
    traffic_segments: list[dict]

    def as_reference(self) -> dict:
        return {
            "synthetic": True,
            "note": "Synthetic sensor registry generated by the AEGIS simulator; not real infrastructure.",
            "weather_stations": self.weather_stations,
            "water_stations": self.water_stations,
            "traffic_segments": self.traffic_segments,
        }

    @classmethod
    def build(cls, cfg: dict, seed: int) -> "SensorNetwork":
        rng = random.Random(seed * 7919 + 17)
        r = cfg["region"]
        g = cfg["generator"]

        def land_point(min_spacing_km: float, taken: list[tuple[float, float]]) -> tuple[float, float]:
            for _ in range(5000):
                lat = rng.uniform(r["min_lat"] + 0.01, r["max_lat"] - 0.01)
                lon = rng.uniform(r["min_lon"] + 0.01, r["max_lon"] - 0.01)
                if not is_on_land(lat, lon):
                    continue
                if all(haversine_km(lat, lon, a, b) >= min_spacing_km for a, b in taken):
                    return round(lat, 5), round(lon, 5)
            raise RuntimeError("could not place a synthetic sensor; reduce counts or spacing")

        weather, taken = [], []
        n_imp = int(g["imperial_weather_stations"])
        for i in range(int(g["weather_stations"])):
            lat, lon = land_point(4.0, taken)
            taken.append((lat, lon))
            imperial = i >= int(g["weather_stations"]) - n_imp
            weather.append({
                "station_id": f"AWS-{i + 1:02d}" if imperial else f"WXM-{i + 1:02d}",
                "name": f"Synthetic weather station {i + 1}",
                "format": "wx-imperial-2" if imperial else "wx-metric-1",
                "lat": lat, "lon": lon,
                "elevation_m": round(rng.uniform(2, 40), 1),
            })

        water = []
        rivers = list(SYNTHETIC_RIVERS.items())
        units = ["m", "m", "cm", "m", "cm", "ft", "m", "cm"]
        for i in range(int(g["water_stations"])):
            river_id, pts = rivers[i % len(rivers)]
            t = (i // len(rivers) + 0.5) / max(1, math.ceil(int(g["water_stations"]) / len(rivers)))
            lat, lon = _interp_polyline(pts, min(0.95, t + rng.uniform(-0.08, 0.08)))
            danger = round(rng.uniform(3.0, 4.5), 2)
            water.append({
                "station_id": f"WLS-{i + 1:02d}",
                "name": f"Synthetic gauge {i + 1}",
                "river_id": river_id,
                "lat": round(lat, 5), "lon": round(lon, 5),
                "unit": units[i % len(units)],
                "danger_level_m": danger,
                "base_level_m": round(danger * rng.uniform(0.30, 0.42), 3),
                # metres of rise per mm of accumulated catchment wetness
                "gain_m_per_mm": round(danger * rng.uniform(0.0050, 0.0068), 5),
            })

        segments, taken_seg = [], []
        for i in range(int(g["traffic_segments"])):
            lat, lon = land_point(1.5, taken_seg)
            taken_seg.append((lat, lon))
            segments.append({
                "segment_id": f"SEG-{i + 1:03d}",
                "source_id": f"TRF-CAM-{i + 1:03d}",
                "lat": lat, "lon": lon,
                "free_flow_kmph": float(rng.choice([30, 40, 50, 60, 70])),
                "base_density": round(rng.uniform(15, 45), 1),
            })
        return cls(weather, water, segments)


@dataclass
class Storm:
    t_start: float        # epoch seconds (simulation clock)
    duration_s: float
    lat0: float
    lon0: float
    v_lat_per_h: float    # degrees per hour
    v_lon_per_h: float
    radius_km: float
    peak_mm_hr: float

    def intensity(self, lat: float, lon: float, t: float) -> float:
        if t < self.t_start or t > self.t_start + self.duration_s:
            return 0.0
        frac = (t - self.t_start) / self.duration_s
        envelope = math.sin(math.pi * frac)
        hours = (t - self.t_start) / 3600.0
        clat = self.lat0 + self.v_lat_per_h * hours
        clon = self.lon0 + self.v_lon_per_h * hours
        dy = (lat - clat) * KM_PER_DEG_LAT
        dx = (lon - clon) * KM_PER_DEG_LAT * math.cos(math.radians(lat))
        d2 = dx * dx + dy * dy
        return self.peak_mm_hr * envelope * math.exp(-d2 / (2.0 * self.radius_km ** 2))


@dataclass
class Environment:
    """Latent environment state. Rain is a closed-form function of
    (location, simulation time); wetness integrates rain with time
    constant ``tau_h`` and drives river levels and flood hazard."""
    grid: ZoneGrid
    network: SensorNetwork
    storms: list[Storm] = field(default_factory=list)
    tau_h: float = 6.0
    drizzle_mm_hr: float = 0.0
    wetness: dict = field(default_factory=dict)   # key -> accumulated mm
    _active: list = field(default_factory=list)
    _active_window: tuple = (0.0, -1.0)

    def refresh_active(self, t_from: float, t_to: float) -> None:
        """Cache the storms overlapping [t_from, t_to] (performance only)."""
        self._active = [s for s in self.storms if s.t_start <= t_to and s.t_start + s.duration_s >= t_from]
        self._active_window = (t_from, t_to)

    def rain(self, lat: float, lon: float, t: float) -> float:
        lo, hi = self._active_window
        candidates = self._active if lo <= t <= hi else self.storms
        total = self.drizzle_mm_hr
        for s in candidates:
            if s.t_start <= t <= s.t_start + s.duration_s:
                total += s.intensity(lat, lon, t)
        return total

    def locations(self) -> Iterable[tuple[str, float, float]]:
        for z in self.grid.zones():
            yield z.zone_id, z.center[0], z.center[1]
        for w in self.network.water_stations:
            yield w["station_id"], w["lat"], w["lon"]

    def step(self, t: float, dt_s: float) -> None:
        """Advance wetness by ``dt_s`` seconds of simulation time (Euler step of
        dW/dt = rain - W/tau)."""
        dt_h = dt_s / 3600.0
        decay = math.exp(-dt_h / self.tau_h)
        for key, lat, lon in self.locations():
            r = self.rain(lat, lon, t)
            w = self.wetness.get(key, 0.0)
            self.wetness[key] = w * decay + r * self.tau_h * (1.0 - decay)

    def warm_up(self, t_end: float, hours: float = 18.0, dt_s: float = 600.0) -> None:
        """Integrate from ``hours`` before ``t_end`` so wetness reflects recent rain."""
        t = t_end - hours * 3600.0
        while t < t_end:
            self.step(t, dt_s)
            t += dt_s

    def river_level_m(self, station: dict) -> float:
        w = self.wetness.get(station["station_id"], 0.0)
        return station["base_level_m"] + station["gain_m_per_mm"] * w

    def flood_hazard(self, key: str) -> float:
        """0..1 latent flood hazard from wetness (0 below 40 mm, 1 at 160 mm)."""
        w = self.wetness.get(key, 0.0)
        return max(0.0, min(1.0, (w - 40.0) / 120.0))

    def nearest_gauge_ratio(self, lat: float, lon: float, radius_km: float = 5.0) -> float:
        best = 0.0
        for s in self.network.water_stations:
            if haversine_km(lat, lon, s["lat"], s["lon"]) <= radius_km:
                best = max(best, self.river_level_m(s) / s["danger_level_m"])
        return best


def historical_storms(rng: random.Random, cfg: dict, t0: float, days: int) -> list[Storm]:
    """Northeast-monsoon-like storm schedule: cells form over the sea and move
    west/south-west across the region. Heavier days occur in clusters."""
    r = cfg["region"]
    storms: list[Storm] = []
    wet_spell = 0.0
    for d in range(days):
        wet_spell = 0.6 * wet_spell + (0.4 if rng.random() < 0.35 else 0.0)
        n = 0 if rng.random() < 0.30 - wet_spell * 0.3 else 1 + int(rng.random() * (2 + 4 * wet_spell))
        for _ in range(n):
            start = t0 + d * 86400 + rng.uniform(0, 86400)
            heavy = rng.random() < 0.15 + 0.4 * wet_spell
            storms.append(Storm(
                t_start=start,
                duration_s=rng.uniform(2.0, 7.0) * 3600.0,
                lat0=rng.uniform(r["min_lat"] - 0.05, r["max_lat"] + 0.05),
                lon0=r["max_lon"] + rng.uniform(0.0, 0.08),
                v_lat_per_h=rng.uniform(-0.03, 0.01),
                v_lon_per_h=-rng.uniform(0.03, 0.08),
                radius_km=rng.uniform(5.0, 14.0),
                peak_mm_hr=rng.uniform(35.0, 95.0) if heavy else rng.uniform(4.0, 30.0),
            ))
    return storms


def live_storms(seed: int, cfg: dict, cycle_sim_s: float, t_from: float, t_to: float) -> list[Storm]:
    """Deterministic storm per live cycle (same seed + wall clock => same weather
    in every producer process). Each cycle one strong cell crosses the region."""
    r = cfg["region"]
    out: list[Storm] = []
    k0, k1 = int(t_from // cycle_sim_s) - 1, int(t_to // cycle_sim_s) + 1
    span_lon = r["max_lon"] - r["min_lon"] + 0.15
    for k in range(k0, k1 + 1):
        rng = random.Random(seed * 1_000_003 + k)
        start = k * cycle_sim_s + rng.uniform(0.0, 0.1) * cycle_sim_s
        dur = cycle_sim_s * rng.uniform(0.75, 0.9)
        out.append(Storm(
            t_start=start, duration_s=dur,
            lat0=rng.uniform(r["min_lat"] + 0.05, r["max_lat"] - 0.05),
            lon0=r["max_lon"] + 0.08,
            v_lat_per_h=rng.uniform(-0.02, 0.02),
            v_lon_per_h=-span_lon / (dur / 3600.0),
            radius_km=rng.uniform(7.0, 12.0),
            peak_mm_hr=rng.uniform(45.0, 85.0),
        ))
        if rng.random() < 0.5:
            out.append(Storm(
                t_start=start + dur * 0.3, duration_s=dur * 0.5,
                lat0=rng.uniform(r["min_lat"], r["max_lat"]), lon0=rng.uniform(r["min_lon"], r["max_lon"]),
                v_lat_per_h=0.0, v_lon_per_h=-0.02, radius_km=rng.uniform(3.0, 6.0),
                peak_mm_hr=rng.uniform(10.0, 30.0),
            ))
    return out
