"""Which dataset the API is serving.

A real-data root written by ``python -m aegis.realdata.ingest`` contains
``dataset_manifest.json`` with ``data_mode = real-historical``; a hybrid root
written by ``python -m producers.hybrid_generator`` has ``data_mode = hybrid``
(real rainfall + synthetic water level, traffic, reports, incidents). Without
that file the data root is the synthetic demo. The dashboard uses this to label every
page, so real and synthetic data are never presented ambiguously.
"""
from __future__ import annotations

from aegis.config import PROJECT_ROOT, data_path
from backend.app.services.parquet_store import read_json

SYNTHETIC = {
    "data_mode": "synthetic",
    "synthetic": True,
    "label": "All AEGIS data in this view is SYNTHETIC (generated by the AEGIS simulator). Risk scores are a "
             "rule-based demonstration index, not an official forecast or warning.",
    "sources": {"simulator": {"data_source": "aegis-simulator", "observation_type": "synthetic",
                              "licence": "project code"}},
    "not_available": {},
}


class DatasetService:
    def __init__(self, cfg: dict):
        self.cfg = cfg

    def info(self) -> dict:
        root = data_path(self.cfg, "generated_dir").parent
        m = read_json(root / "dataset_manifest.json")
        try:
            shown = str(root.relative_to(PROJECT_ROOT))
        except ValueError:
            shown = str(root)
        if not m:
            return {**SYNTHETIC, "data_root": shown}
        return {**m, "data_root": shown}

    def origin_note(self) -> str:
        mode = self.info().get("data_mode")
        if mode == "synthetic":
            return ("live-stream = Structured Streaming output; batch-historical = batch ETL over the "
                    "synthetic 60-day backfill.")
        if mode == "hybrid":
            return ("batch-historical = batch ETL over real rainfall plus SYNTHETIC water level, traffic, reports "
                    "and incidents simulated from that rainfall (historical, not live). No live stream is served "
                    "in this mode.")
        return ("batch-historical = batch ETL over the imported real datasets (historical, not live). "
                "No live stream is served in this mode.")
