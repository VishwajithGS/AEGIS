import React from "react";
import { api } from "../services/api.js";
import { useApi } from "../hooks/useApi.js";
import { Card, ErrorBox, Loading, OriginBadge, RiskBadge, Stat } from "../components/ui.jsx";
import { RISK_COLORS, RISK_ORDER, dataMode, fmt, fmtInt, fmtTime, timeAgo } from "../constants.js";

const partList = (parts) => parts && Object.keys(parts).length > 0 && (
  <ul className="small">
    {Object.entries(parts).map(([k, v]) => <li key={k}><strong>{k.replace(/_/g, " ")}</strong>: {v}</li>)}
  </ul>
);

export default function Overview({ alerts, refreshKey, onOpenZone }) {
  const { data, error, loading } = useApi(() => api.overview(), [refreshKey], 20000);
  if (loading && !data) return <Loading what="overview" />;
  if (error && !data) return <ErrorBox error={error} what="overview" />;
  const d = data;
  const mode = dataMode(d.dataset);
  const cats = d.zones.category_counts || {};
  const total = d.zones.total || 1;
  return (
    <div className="page">
      {mode === "synthetic" && (
        <div className="banner info">
          All AEGIS data is <strong>synthetic</strong> (generated by the AEGIS simulator). Risk scores are a rule-based
          demonstration index, not an official forecast or warning. {d.data_origin_note}
        </div>
      )}
      {mode === "hybrid" && (
        <div className="banner hybrid">
          <strong>Hybrid data</strong> ({d.dataset.period ? `${d.dataset.period.start} – ${d.dataset.period.end}` : ""}).{" "}
          {d.dataset.label} {d.data_origin_note}
          <div className="small" style={{ marginTop: 6 }}><strong>Real:</strong></div>
          {partList(d.dataset.real_parts)}
          <div className="small" style={{ marginTop: 6 }}><strong>SYNTHETIC:</strong></div>
          {partList(d.dataset.synthetic_parts)}
        </div>
      )}
      {mode !== "synthetic" && mode !== "hybrid" && (
        <div className="banner real">
          <strong>Real historical data</strong> ({d.dataset.period ? `${d.dataset.period.start} – ${d.dataset.period.end}` : ""}).{" "}
          {d.dataset.label} {d.data_origin_note}
          {partList(d.dataset.not_available)}
        </div>
      )}
      <div className="stats-grid">
        <Stat label="Stream events archived (bronze)" value={fmtInt(d.counts.stream_events_archived)} hint="raw Kafka records" />
        <Stat label="Stream events processed (silver)" value={fmtInt(d.counts.stream_events_processed)} hint="validated + de-duplicated" />
        <Stat label="Batch records processed" value={fmtInt(d.counts.batch_records_processed)} hint={`${fmtInt(d.counts.batch_silver_rows)} silver rows`} />
        <Stat label="Live reports (last hour)" value={fmtInt(d.incidents.live_reports_last_hour)} hint={`${fmtInt(d.incidents.live_reports_last_24h)} in 24 h`} />
        <Stat label="Incidents & reports (all)" value={fmtInt(d.incidents.total)}
              hint={`${fmtInt(d.incidents.archived_incidents)} archived · ${fmtInt(d.incidents.public_reports)} reports`} />
        <Stat label="Live rejected rate" value={d.data_quality.live_rejected_pct != null ? `${fmt(d.data_quality.live_rejected_pct, 2)}%` : "—"}
              hint={`batch: ${d.data_quality.batch_rejected_pct != null ? fmt(d.data_quality.batch_rejected_pct, 2) + "%" : "—"}`}
              tone={d.data_quality.live_rejected_pct > 15 ? "warn" : undefined} />
        <Stat label="Streaming job" value={d.processing.streaming_running ? "running" : d.processing.streaming_state || "not running"}
              tone={d.processing.streaming_running ? "ok" : "bad"} hint={`updated ${timeAgo(d.processing.updated_at)}`} />
        <Stat label="ML model" value={d.model.state} hint={d.model.version || "not trained"} tone={d.model.state === "ready" ? "ok" : "warn"} />
      </div>

      <div className="grid-2">
        <Card title="Zones by rule-based risk category" subtitle={`${d.zones.live_zones} zones with live assessments (${d.zones.fresh_live_zones} fresh) · latest window end ${fmtTime(d.zones.latest_window_end)}`}>
          <div className="stack-bar">
            {RISK_ORDER.filter((c) => cats[c]).map((c) => (
              <span key={c} style={{ width: `${(100 * cats[c]) / total}%`, background: RISK_COLORS[c] }} title={`${c}: ${cats[c]}`} />
            ))}
          </div>
          <ul className="legend">
            {RISK_ORDER.filter((c) => cats[c]).map((c) => (
              <li key={c}>
                <RiskBadge category={c} /> {cats[c]} zones
              </li>
            ))}
          </ul>
        </Card>
        <Card title="Recent alerts" subtitle="Raised by the dashboard when a zone update is High or Critical. Not sent to any external service.">
          {alerts.length === 0 ? (
            <p className="muted">No alerts received in this browser session.</p>
          ) : (
            <ul className="alert-list">
              {alerts.slice(0, 8).map((a) => (
                <li key={a.alert_id} onClick={() => onOpenZone(a.zone_id)}>
                  <RiskBadge category={a.risk_category} score={a.risk_score} /> <strong>{a.zone_id}</strong>
                  <span className="muted small"> · window {fmtTime(a.window_start)} · raised {timeAgo(a.raised_at)}</span>
                  <div className="small">{a.explanation}</div>
                </li>
              ))}
            </ul>
          )}
        </Card>
      </div>
      <Card title="Incident categories (all sources)">
        <div className="chips">
          {Object.entries(d.incidents.by_category || {}).map(([k, v]) => (
            <span key={k} className="chip">
              {k}: <strong>{fmtInt(v)}</strong>
            </span>
          ))}
        </div>
        <p className="muted small">
          Latest incident timestamp: {fmtTime(d.incidents.latest_event_time)} · generated {fmtTime(d.generated_at)}{" "}
          {mode !== "real-historical"
            ? <OriginBadge origin="synthetic" />
            : "· no verified real incident or report source in this mode (see banner)"}
        </p>
      </Card>
    </div>
  );
}
